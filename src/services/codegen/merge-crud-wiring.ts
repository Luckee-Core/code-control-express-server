import type { CrudTable } from './crud-operations';

/**
 * Merges new tables into the files that wire CRUD together, keeping everything already there.
 * Each function returns the new content, or null when nothing changes, and `{ error }` when the
 * file does not have the expected shape (the caller reports it instead of guessing).
 */

export type MergeResult = { content: string } | { unchanged: true } | { error: string };

/** Inserts lines after the last top-level `import …;` statement (or at the top). */
const addImports = (source: string, lines: string[]): string => {
  const missing = lines.filter((line) => !source.includes(line));
  if (missing.length === 0) return source;
  const importRegex = /^import[\s\S]*?;\s*$/gm;
  let lastEnd = -1;
  for (let match = importRegex.exec(source); match; match = importRegex.exec(source)) {
    lastEnd = match.index + match[0].length;
  }
  if (lastEnd === -1) return `${missing.join('\n')}\n${source}`;
  return `${source.slice(0, lastEnd)}\n${missing.join('\n')}${source.slice(lastEnd)}`;
};

/** storage src/services/storage/build-storage-operation-registry.ts: import each barrel and add it to `modules`. */
export const mergeStorageRegistry = (existing: string | null, tables: CrudTable[]): MergeResult => {
  if (existing === null) return { error: 'build-storage-operation-registry.ts not found (is this repo from the storage template?)' };
  const match = /(const modules\s*:\s*Record<string,\s*unknown>\[\]\s*=\s*\[)([\s\S]*?)(\];)/.exec(existing);
  if (!match) return { error: 'build-storage-operation-registry.ts has no `const modules: Record<string, unknown>[] = [...]` list' };

  const listed = match[2].split(',').map((item) => item.trim()).filter(Boolean);
  const missing = tables.filter((crud) => !listed.includes(crud.names.thingsCamel));
  if (missing.length === 0) return { unchanged: true };

  const items = [...listed, ...missing.map((crud) => crud.names.thingsCamel)];
  const modulesLine = `${match[1]}${items.join(', ')}${match[3]}`;
  const withModules = existing.slice(0, match.index) + modulesLine + existing.slice(match.index + match[0].length);
  return {
    content: addImports(
      withModules,
      missing.map((crud) => `import * as ${crud.names.thingsCamel} from '../../data/${crud.names.folder}';`),
    ),
  };
};

/** express src/services/api-data/router.ts: create it, or add each table's router. */
export const mergeExpressDataRouter = (existing: string | null, tables: CrudTable[]): MergeResult => {
  const importLine = (crud: CrudTable) => `import { create${crud.names.Things}Router } from '../${crud.names.folder}/router';`;
  const useLine = (crud: CrudTable) => `  router.use('/${crud.names.folder}', create${crud.names.Things}Router());`;

  if (existing === null) {
    return {
      content: [
        "import { Router } from 'express';",
        ...tables.map(importLine),
        '',
        '/**',
        ' * Mounts every table router under /api/data.',
        ' */',
        'export const createDataRouter = (): Router => {',
        '  const router = Router();',
        ...tables.map(useLine),
        '  return router;',
        '};',
        '',
      ].join('\n'),
    };
  }
  const missing = tables.filter((crud) => !existing.includes(`create${crud.names.Things}Router()`));
  if (missing.length === 0) return { unchanged: true };
  const returnIndex = existing.lastIndexOf('  return router;');
  if (returnIndex === -1) return { error: 'src/services/api-data/router.ts has no `  return router;` line' };
  const withUses = `${existing.slice(0, returnIndex)}${missing.map(useLine).join('\n')}\n${existing.slice(returnIndex)}`;
  return { content: addImports(withUses, missing.map(importLine)) };
};

const EXPRESS_INDEX_IMPORT = "import { createDataRouter } from './src/services/api-data/router';";
const EXPRESS_INDEX_MOUNT = "app.use('/api/data', createDataRouter());";

/** express index.ts: mount createDataRouter() at /api/data before error handling. */
export const mergeExpressIndex = (existing: string | null): MergeResult => {
  if (existing === null) return { error: 'index.ts not found at the repo root' };
  if (existing.includes('createDataRouter()')) return { unchanged: true };
  const anchors = ['// Error handling middleware', 'import { setupErrorHandling }', 'setupErrorHandling(app)'];
  const anchor = anchors.map((text) => existing.indexOf(text)).find((index) => index !== -1);
  if (anchor === undefined) return { error: 'index.ts: could not find where error handling starts to mount /api/data before it' };
  const lineStart = existing.lastIndexOf('\n', anchor) + 1;
  const block = `// Table CRUD routes (generated by Code Control)\n${EXPRESS_INDEX_IMPORT}\n${EXPRESS_INDEX_MOUNT}\n\n`;
  return { content: existing.slice(0, lineStart) + block + existing.slice(lineStart) };
};

/** web src/store/reducer.ts: add each dump to combineReducers. */
export const mergeWebReducer = (existing: string | null, tables: CrudTable[]): MergeResult => {
  if (existing === null) return { error: 'src/store/reducer.ts not found (is this repo from the nextjs template?)' };
  const missing = tables.filter((crud) => !existing.includes(`${crud.names.thingsCamel}Reducer`));
  if (missing.length === 0) return { unchanged: true };
  const match = /combineReducers\(\{\s*\n?/.exec(existing);
  if (!match) return { error: 'src/store/reducer.ts has no combineReducers({ … })' };
  const insertAt = match.index + match[0].length;
  const entries = missing.map((crud) => `  ${crud.names.thingsCamel}: ${crud.names.thingsCamel}Reducer,\n`).join('');
  const withEntries = existing.slice(0, insertAt) + entries + existing.slice(insertAt);
  return {
    content: addImports(
      withEntries,
      missing.map((crud) => `import { ${crud.names.thingsCamel}Reducer } from './dumps/${crud.names.folder}';`),
    ),
  };
};
