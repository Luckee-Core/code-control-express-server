import type { ProposedTable } from '../../model/data-model-proposal';
import { indexName } from './naming';
import type { CodegenVocabulary, RenderColumn } from './types';

const ON_DELETE_SQL: Record<RenderColumn['on_delete'], string> = {
  none: '',
  cascade: ' ON DELETE CASCADE',
  set_null: ' ON DELETE SET NULL',
  restrict: ' ON DELETE RESTRICT',
};

const quote = (value: string): string => `'${value.replace(/'/g, "''")}'`;

/** A default expression from the model, refusing anything that could end the statement. */
const safeDefault = (value: string): string => (value.includes(';') ? '' : value.trim());

const renderColumnLine = (column: RenderColumn): string => {
  const parts = [column.name, column.sql_type];
  if (column.not_null) parts.push('NOT NULL');
  const defaultSql = safeDefault(column.default_sql);
  if (defaultSql) parts.push(`DEFAULT ${defaultSql}`);
  if (column.is_unique) parts.push('UNIQUE');
  if (column.enum_values.length > 0) {
    parts.push(`CHECK (${column.name} IN (${column.enum_values.map(quote).join(', ')}))`);
  }
  if (column.references_table) {
    parts.push(`REFERENCES ${column.references_table} (id)${ON_DELETE_SQL[column.on_delete]}`);
  }
  return parts.join(' ');
};

/** One-line SQL comment text (no newlines). */
const comment = (text: string): string => text.replace(/\s+/g, ' ').trim();

/**
 * Renders `CREATE TABLE IF NOT EXISTS` for one table plus its indexes. Standard columns come
 * from standard_columns: `id` first, the rest (timestamps) last. No functions or triggers.
 */
export const renderMigration = (input: {
  table: ProposedTable;
  columns: RenderColumn[];
  vocabulary: CodegenVocabulary;
  version: number;
}): string => {
  const { table, columns, vocabulary, version } = input;
  const standard = [...vocabulary.standard_columns].sort((a, b) => a.sort_order - b.sort_order);
  const leading = standard.filter((column) => column.name === 'id').map((column) => column.sql_definition);
  const trailing = standard.filter((column) => column.name !== 'id').map((column) => column.sql_definition);
  const lines = [...leading, ...columns.map(renderColumnLine), ...trailing];

  const indexed = columns.filter((column) => column.is_indexed && !column.is_unique);
  const indexes = indexed.map(
    (column) => `CREATE INDEX IF NOT EXISTS ${indexName(table.name, column.name)} ON ${table.name} (${column.name});`,
  );

  return [
    `-- ${table.name}: ${comment(table.purpose)}`,
    `-- Generated by Code Control from data model v${version} (archetype: ${table.archetype}, lifecycle: ${table.lifecycle}).`,
    `-- updated_at is set by data-layer CRUD; no SQL functions or triggers.`,
    `CREATE TABLE IF NOT EXISTS ${table.name} (`,
    lines.map((line) => `  ${line}`).join(',\n'),
    ');',
    ...(indexes.length > 0 ? ['', ...indexes] : []),
    '',
  ].join('\n');
};
