import type { ProposedTable } from '../../model/data-model-proposal';
import { toPascalCase } from './naming';
import type { CodegenVocabulary, RenderColumn } from './types';

const quote = (value: string): string => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const jsdoc = (text: string, indent = ''): string[] => {
  const value = text.replace(/\s+/g, ' ').replace(/\*\//g, '* /').trim();
  return value ? [`${indent}/** ${value} */`] : [];
};

const unionName = (entityPascal: string, column: RenderColumn): string => `${entityPascal}${toPascalCase(column.name)}`;

const fieldType = (entityPascal: string, column: RenderColumn): string => {
  const base = column.enum_values.length > 0 ? unionName(entityPascal, column) : column.ts_type;
  return column.not_null ? base : `${base} | null`;
};

/** NOT NULL with no default: the caller must provide it on create. */
const isRequiredOnCreate = (column: RenderColumn): boolean => column.not_null && !column.default_sql.trim();

/**
 * Renders src/model/{entity}/index.ts: enum unions, the row type (standard columns first),
 * Create{Entity}Input and Update{Entity}Input. Types only, `type` never `interface`.
 */
export const renderModel = (input: {
  table: ProposedTable;
  columns: RenderColumn[];
  vocabulary: CodegenVocabulary;
}): string => {
  const { table, columns, vocabulary } = input;
  const entity = toPascalCase(table.entity);
  const standard = [...vocabulary.standard_columns].sort((a, b) => a.sort_order - b.sort_order);

  const unions = columns
    .filter((column) => column.enum_values.length > 0)
    .flatMap((column) => [
      ...jsdoc(`Allowed values for ${table.name}.${column.name}.`),
      `export type ${unionName(entity, column)} = ${column.enum_values.map(quote).join(' | ')};`,
      '',
    ]);

  const rowFields = [
    ...standard.map((column) => `  ${column.name}: ${column.ts_type.trim() || 'string'};`),
    ...columns.flatMap((column) => [...jsdoc(column.description, '  '), `  ${column.name}: ${fieldType(entity, column)};`]),
  ];

  const createFields = columns.map(
    (column) => `  ${column.name}${isRequiredOnCreate(column) ? '' : '?'}: ${fieldType(entity, column)};`,
  );
  const updateFields = columns.map((column) => `  ${column.name}?: ${fieldType(entity, column)};`);

  return [
    `// Generated by Code Control from the approved data model. Identical in storage, express and web.`,
    '',
    ...unions,
    ...jsdoc(`Row in ${table.name}. ${table.purpose}`),
    `export type ${entity} = {`,
    ...rowFields,
    '};',
    '',
    ...jsdoc(`Input for create${entity}.`),
    `export type Create${entity}Input = {`,
    ...createFields,
    '};',
    '',
    ...jsdoc(`Input for update${entity} (only the fields to change).`),
    `export type Update${entity}Input = {`,
    ...updateFields,
    '};',
    '',
  ].join('\n');
};
