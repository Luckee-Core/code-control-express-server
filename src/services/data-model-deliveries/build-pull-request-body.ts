import type { DataModelProposal, DataModelProposalContent } from '../../model/data-model-proposal';
import type { CodegenRole, RenderedFile } from '../codegen';

const ROLE_NOTE: Record<CodegenRole, string> = {
  storage:
    'After merging, apply the new migrations with `npm run db:apply-migrations -- <NNN> …` (the numbers below) and restart storage.',
  express: 'Model types only; invoke wrappers and services come in a later Code Control step.',
  web: 'Model types only; src/api, dumps and thunks come in a later Code Control step.',
};

/**
 * Markdown body for a data-model pull request: tables, files and what to do after merging.
 */
export const buildPullRequestBody = (input: {
  proposal: DataModelProposal;
  content: DataModelProposalContent;
  role: CodegenRole;
  files: RenderedFile[];
}): string => {
  const { proposal, content, role, files } = input;
  return [
    `Generated by **Code Control** from data model **v${proposal.version}** (approved${proposal.approved_at ? ` ${proposal.approved_at.slice(0, 10)}` : ''}).`,
    '',
    content.summary ? `> ${content.summary.replace(/\n+/g, ' ')}` : '',
    '',
    '### Tables',
    ...content.tables.map((table) => `- \`${table.name}\` (${table.archetype}, ${table.lifecycle}) — ${table.purpose}`),
    '',
    '### Files',
    ...files.map((file) => `- ${file.action === 'create' ? 'add' : 'update'} \`${file.path}\``),
    '',
    ROLE_NOTE[role],
    '',
    'Do not hand-edit these files; change the data model in Code Control and deliver again.',
  ]
    .filter((line, index, lines) => !(line === '' && lines[index - 1] === ''))
    .join('\n');
};
